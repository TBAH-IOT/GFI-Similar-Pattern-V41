const assert = require('node:assert/strict');
const {timeline,createNotificationSession} = require('../static/pattern-presentation.js');
const make = (id,time,status='EXPIRED',name='Diamond_Top',start=time-100) => ({id,name,status,tf:'1h',direction:'LONG',detected_at:time,available_at:time+10,points:[{time:start},{time:time-5}]});
const items=[make('a',1000),make('b',900,'OPEN'),make('c',800),make('d',600),make('e',400)];
let view=timeline(items);
assert.equal(view.main.id,'a','Navigation defaults to the most recent confirmed pattern, regardless of old open trades');
assert.equal(view.newer,null);
assert.equal(view.older.id,'b');
view=timeline(items,'c');
assert.equal(view.main.id,'c');
assert.equal(view.older.id,'d');
assert.equal(view.newer.id,'b');
assert.equal(view.index,2);
assert.equal(timeline(items,'e').older,null);
assert.equal(timeline([],null).main,null);
const twins=[make('first',1000,'EXPIRED','Broadening_Bottom',700),make('duplicate',990,'EXPIRED','Broadening_Bottom',710),make('other',600)];
assert.equal(timeline(twins).total,3,'Do not hide model results with a visual overlap heuristic');
assert.equal(timeline(Array.from({length:150},(_,i)=>make(String(i),i*1000))).total,150,'Never truncate the navigation to 80 patterns');
const notifications=createNotificationSession();
assert.deepEqual(notifications.observe('1h',items,1100*1000,3600),[],'Initial history is not a new notification');
const fresh=make('fresh',1200,'OPEN','Wedge_Falling');
assert.equal(notifications.observe('1h',[fresh,...items],1220*1000,3600)[0].id,'fresh');
assert.deepEqual(notifications.observe('1h',[fresh,...items],1230*1000,3600),[],'A repeated refresh must not notify twice');
const rediscovered={...fresh,id:'new-id',detected_at:1210,available_at:1220};
assert.deepEqual(notifications.observe('1h',[rediscovered,...items],1240*1000,3600),[],'The same pivot structure with a different id is not a new opportunity');
const stale=make('stale',1300,'EXPIRED','Wedge_Rising');
assert.deepEqual(notifications.observe('1h',[stale,...items],20000*1000,3600),[],'Rediscovered old history must not be labelled fresh');
assert.deepEqual(notifications.observe('15m',[fresh],1250*1000,900),[],'Changing timeframe starts with a quiet baseline');
console.log('PASS chronological navigation: every result, oldest/newest bounds, selected position, no visual suppression; fresh-only notifications');
